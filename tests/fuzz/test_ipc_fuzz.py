"""IPC fuzz harness — validates daemon robustness to malformed input.

Tests that the daemon:
- Never crashes on random byte strings or malformed JSON
- Never returns success (decision: pass) on obviously malformed input
- Does not leak file descriptors
- Remains responsive to health checks after fuzzing

This uses hypothesis to generate random inputs. Smoke tests run for ~60s per PR;
a separate nightly workflow runs for ≥1 hour in CI.

Reference: TC-027-04, TC-027-05, TC-027-06
"""

import contextlib
import json
import os
import socket
import subprocess
import tempfile
import time
from collections.abc import Generator
from pathlib import Path

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st


def start_daemon(socket_path: str, db_path: str, timeout: float = 10.0) -> subprocess.Popen:
    """Start the armor daemon as a subprocess.

    Args:
        socket_path: Path to the Unix socket
        db_path: Path to the SQLite database
        timeout: Max time to wait for daemon to start listening

    Returns:
        Popen instance for the daemon process

    Raises:
        TimeoutError: If daemon doesn't start within timeout
    """
    proc = subprocess.Popen(
        ["uv", "run", "armor", "daemon", "--socket", socket_path, "--db", db_path],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )

    # Wait for socket to be created
    start_time = time.time()
    while time.time() - start_time < timeout:
        if Path(socket_path).exists():
            time.sleep(0.1)  # Give daemon a moment to bind
            return proc
        time.sleep(0.05)

    proc.terminate()
    try:
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait()
    raise TimeoutError(f"Daemon failed to start within {timeout}s")


def send_raw(socket_path: str, data: bytes, timeout: float = 2.0) -> bytes:
    """Send raw bytes to the daemon socket and read response.

    Args:
        socket_path: Path to the Unix socket
        data: Raw bytes to send
        timeout: Socket timeout in seconds

    Returns:
        Response bytes (may be empty if connection closed)

    Raises:
        socket.timeout: If response not received within timeout
    """
    sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    sock.settimeout(timeout)
    try:
        sock.connect(socket_path)
        sock.sendall(data)

        # Try to read response
        response_data = b""
        try:
            while True:
                chunk = sock.recv(4096)
                if not chunk:
                    break
                response_data += chunk
                # Stop after first line (newline-delimited JSON)
                if b"\n" in response_data:
                    break
        except TimeoutError:
            # Timeout reading is OK; may be a slow response
            pass

        return response_data
    finally:
        sock.close()


def get_fd_count() -> int:
    """Get the current process file descriptor count.

    Returns:
        Number of open file descriptors in the calling process
    """
    try:
        return len(os.listdir("/proc/self/fd"))
    except FileNotFoundError:
        # Fallback for non-Linux systems (macOS, etc.)
        return -1


