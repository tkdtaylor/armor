class TestIPCFuzz:
    """IPC fuzz tests using hypothesis."""

    @given(st.binary(min_size=1, max_size=1024))
    @settings(max_examples=10, deadline=None, suppress_health_check=[HealthCheck.function_scoped_fixture])
    def test_random_bytes_never_crash(self, random_bytes: bytes) -> None:
        """TC-027-04: Daemon never crashes on random byte input.

        Sends random bytes to the daemon socket. The daemon should:
        - Not crash
        - Return an error response or close the connection gracefully
        - Remain responsive to subsequent health checks

        Args:
            random_bytes: Random byte string generated by hypothesis
        """
        with tempfile.TemporaryDirectory() as tmpdir:
            temp_dir = Path(tmpdir)
            socket_path = str(temp_dir / "armor.sock")
            db_path = str(temp_dir / "test.db")

            # Start daemon fresh for each test
            daemon = start_daemon(socket_path, db_path)

            try:
                # Send random bytes
                response = b""
                with contextlib.suppress(TimeoutError, ConnectionResetError, BrokenPipeError):
                    response = send_raw(socket_path, random_bytes, timeout=1.0)

                # Daemon should still be running
                assert daemon.poll() is None, "Daemon crashed after random bytes"

                # If we got a response, it should be JSON (not a crash dump)
                if response and response.startswith(b"{"):
                    with contextlib.suppress(json.JSONDecodeError, UnicodeDecodeError, ValueError):
                        resp_json = json.loads(response.split(b"\n")[0])
                        # Response should have some basic structure
                        assert isinstance(resp_json, dict)
            finally:
                daemon.terminate()
                try:
                    daemon.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    daemon.kill()
                    daemon.wait()

    @given(st.binary(min_size=1, max_size=1024))
    @settings(max_examples=10, deadline=None, suppress_health_check=[HealthCheck.function_scoped_fixture])
    def test_malformed_never_succeeds(self, random_bytes: bytes) -> None:
        """TC-027-05: Daemon never returns success on malformed input.

        Sends random/malformed byte strings and verifies:
        - No response has decision: 'pass'
        - Either an error response or connection reset

        Args:
            random_bytes: Random byte string generated by hypothesis
        """
        with tempfile.TemporaryDirectory() as tmpdir:
            temp_dir = Path(tmpdir)
            socket_path = str(temp_dir / "armor.sock")
            db_path = str(temp_dir / "test.db")

            daemon = start_daemon(socket_path, db_path)

            try:
                # Send malformed data
                response = b""
                with contextlib.suppress(TimeoutError, ConnectionResetError, BrokenPipeError):
                    response = send_raw(socket_path, random_bytes, timeout=1.0)

                # If we got a valid JSON response, it should not be a success
                if response and response.startswith(b"{"):
                    with contextlib.suppress(json.JSONDecodeError, ValueError, KeyError):
                        resp_json = json.loads(response.split(b"\n")[0])
                        if "verdict" in resp_json:
                            # Malformed input should not get a 'pass' verdict
                            assert resp_json["verdict"] != "pass", (
                                f"Random bytes received a pass verdict: {random_bytes!r}"
                            )

                assert daemon.poll() is None, "Daemon crashed on malformed input"
            finally:
                daemon.terminate()
                try:
                    daemon.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    daemon.kill()
                    daemon.wait()

    def test_fd_leak_smoke(self, temp_dir: Path) -> None:
        """TC-027-06: Fuzz burst does not leak file descriptors.

        Sends 30 requests in rapid succession and measures the FD count
        before and after. The delta should be small (≤5 for connection churn).

        Args:
            temp_dir: Temporary directory for socket/db
        """
        socket_path = str(temp_dir / "armor.sock")
        db_path = str(temp_dir / "test.db")

        daemon = start_daemon(socket_path, db_path)

        try:
            # Sample FD count before fuzz burst
            fd_count_before = get_fd_count()

            # Send 30 requests (mix of valid and malformed)
            for i in range(30):
                data = b"X" * (i % 256)  # Varying lengths of garbage
                with contextlib.suppress(TimeoutError, ConnectionResetError, BrokenPipeError):
                    send_raw(socket_path, data, timeout=0.5)

            # Allow daemon time to clean up
            time.sleep(0.5)

            # Sample FD count after
            fd_count_after = get_fd_count()

            # On non-Linux, skip this assertion
            if fd_count_before >= 0 and fd_count_after >= 0:
                fd_delta = fd_count_after - fd_count_before
                # Allow small increase for connection pool or internal state
                assert fd_delta <= 5, (
                    f"FD count increased by {fd_delta} (before={fd_count_before}, after={fd_count_after})"
                )

            assert daemon.poll() is None, "Daemon crashed during FD test"
        finally:
            daemon.terminate()
            try:
                daemon.wait(timeout=5)
            except subprocess.TimeoutExpired:
                daemon.kill()
                daemon.wait()

    def test_daemon_responsive_after_fuzz(self, temp_dir: Path) -> None:
        """Daemon remains responsive after receiving random/malformed input.

        Sends 50 malformed requests, then sends a valid request and
        verifies the daemon responds correctly.

        Args:
            temp_dir: Temporary directory for socket/db
        """
        socket_path = str(temp_dir / "armor.sock")
        db_path = str(temp_dir / "test.db")

        daemon = start_daemon(socket_path, db_path)

        try:
            # Fuzz burst
            for i in range(50):
                data = b"\x00" * (1 + (i % 100))
                with contextlib.suppress(TimeoutError, ConnectionResetError, BrokenPipeError):
                    send_raw(socket_path, data, timeout=0.2)

            # Now send a valid request
            valid_request = {
                "v": 1,
                "op": "check.input",
                "payload": {"text": "test after fuzz"},
            }
            response_data = send_raw(socket_path, json.dumps(valid_request).encode() + b"\n")

            # Should get a valid response
            assert response_data, "No response to valid request after fuzz"
            if response_data.startswith(b"{"):
                resp_json = json.loads(response_data.split(b"\n")[0])
                assert "verdict" in resp_json, f"Response missing verdict: {resp_json}"
                assert resp_json["verdict"] in ("pass", "block", "error", "advisory"), (
                    f"Invalid verdict: {resp_json['verdict']}"
                )

            assert daemon.poll() is None, "Daemon died after fuzz burst"
        finally:
            daemon.terminate()
            try:
                daemon.wait(timeout=5)
            except subprocess.TimeoutExpired:
                daemon.kill()
                daemon.wait()
