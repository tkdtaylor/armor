@pytest.fixture
def temp_db():
    """Create a temporary database with schema."""
    with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
        db_path = f.name
    run_migrations(db_path)
    yield db_path
    Path(db_path).unlink(missing_ok=True)


@pytest.fixture
def temp_dir():
    """Create a temporary directory for key files."""
    with tempfile.TemporaryDirectory() as tmpdir:
        yield tmpdir


@pytest.mark.asyncio
async def test_write_encrypts(temp_db, temp_dir):
    """Write encrypts the payload."""
    key_path = os.path.join(temp_dir, ".key")
    store = QuarantineStore(temp_db, key_path=key_path)

    input_text = "sensitive input data"
    quarantine_id = await store.write(input_text)

    assert quarantine_id is not None

    # Get the encrypted data from DB
    conn = sqlite3.connect(temp_db)
    cursor = conn.cursor()
    cursor.execute("SELECT input_text FROM QuarantinedPayload WHERE id = ?", (quarantine_id,))
    row = cursor.fetchone()

    encrypted_text = row[0]

    # Encrypted text should not contain plaintext
    assert input_text not in encrypted_text

    conn.close()


@pytest.mark.asyncio
async def test_decrypt_round_trip(temp_db, temp_dir):
    """Encrypt and decrypt returns original text."""
    key_path = os.path.join(temp_dir, ".key")
    store = QuarantineStore(temp_db, key_path=key_path)

    input_text = "secret data for decryption"
    quarantine_id = await store.write(input_text)

    # Get encrypted text from DB
    conn = sqlite3.connect(temp_db)
    cursor = conn.cursor()
    cursor.execute("SELECT input_text FROM QuarantinedPayload WHERE id = ?", (quarantine_id,))
    row = cursor.fetchone()
    encrypted_text = row[0]
    conn.close()

    # Decrypt
    decrypted = await store.decrypt_payload(encrypted_text)
    assert decrypted == input_text


